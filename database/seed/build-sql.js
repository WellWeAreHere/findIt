// Generates database/mysql/05_seed.sql from data.js.
// Usage: npm run db:build-seed
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import bcrypt from 'bcryptjs';
import {
  SEED_PASSWORD, admins, students, studentId, categories, buildings, reports, claims, closedReports,
} from './data.js';

const OUT = fileURLToPath(new URL('../mysql/05_seed.sql', import.meta.url));
const ADMIN_ID = 1;

const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
};
const row = (values) => `(${values.map(q).join(', ')})`;
const insert = (table, columns, rows) =>
  `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n  ${rows.map(row).join(',\n  ')};\n`;

// Lookup tables mirroring the AUTO_INCREMENT ids the inserts will produce
const itemIds = new Map();
const itemRows = [];
categories.forEach((c, ci) => c.items.forEach((name) => {
  itemRows.push([ci + 1, name]);
  itemIds.set(name, itemRows.length);
}));

const locationIds = new Map();
const locationRows = [];
buildings.forEach(([, , locs], bi) => locs.forEach(([key, floor, area]) => {
  locationRows.push([bi + 1, floor, area]);
  locationIds.set(key, locationRows.length);
}));

const need = (map, key, what) => {
  if (!map.has(key)) throw new Error(`Unknown ${what}: ${key}`);
  return map.get(key);
};

const hash = bcrypt.hashSync(SEED_PASSWORD, 10);
const out = [];

out.push(`-- =====================================================================
-- FindIt - seed data (GENERATED by database/seed/build-sql.js - do not edit)
-- All seed accounts use the password: ${SEED_PASSWORD}
-- =====================================================================
SET @app_user_id = NULL;
`);

out.push(insert('users', ['name', 'email', 'srn', 'password_hash', 'role', 'created_at'], [
  ...admins.map((a) => [a.name, a.email, null, hash, 'ADMIN', '2026-07-01 09:00:00']),
  ...students.map((s, i) => [s.name, s.email, s.srn, hash, 'STUDENT', `2026-07-${String(10 + (i % 15)).padStart(2, '0')} 10:00:00`]),
]));

out.push(insert('categories', ['category_name', 'description'], categories.map((c) => [c.name, c.description])));
out.push(insert('items', ['category_id', 'item_name'], itemRows));
out.push(insert('buildings', ['building_name', 'zone'], buildings.map(([name, zone]) => [name, zone])));
out.push(insert('locations', ['building_id', 'floor', 'area'], locationRows));

out.push(insert('reports',
  ['report_id', 'user_id', 'item_id', 'location_id', 'custody_location_id', 'report_type', 'description', 'report_date', 'created_at', 'updated_at'],
  reports.map(([type, student, item, loc, date, summary, , , custody], i) => {
    const created = `${date} ${String(9 + (i % 10)).padStart(2, '0')}:${String((i * 7) % 60).padStart(2, '0')}:00`;
    return [i + 1, studentId(student), need(itemIds, item, 'item'), need(locationIds, loc, 'location'),
      custody ? need(locationIds, custody, 'location') : null, type, summary, date, created, created];
  })));

out.push(`
-- Claims are inserted as PENDING; decisions go through the same stored
-- procedures the application uses.
`);
out.push(insert('claims', ['claim_id', 'report_id', 'claimant_id', 'lost_report_id', 'claim_description', 'created_at'],
  claims.map(([report, student, lost, text], i) => {
    const day = reports[report - 1][4];
    return [i + 1, report, studentId(student), lost, text, `${day} 20:00:00`];
  })));

out.push(insert('notifications', ['user_id', 'related_report_id', 'message', 'notification_type', 'is_read', 'created_at'],
  claims.map(([report], i) => {
    const [, finder, item, , day] = reports[report - 1];
    return [studentId(finder), report, `Someone has claimed the ${item} you found. An admin will verify it.`, 'CLAIM_RECEIVED', i % 3 === 0 ? 1 : 0, `${day} 20:00:00`];
  })));

claims.forEach(([, student, , , outcome, note], i) => {
  const id = i + 1;
  if (outcome === 'APPROVE') out.push(`CALL sp_approve_claim(${id}, ${ADMIN_ID}, ${q(note)});`);
  if (outcome === 'REJECT') out.push(`CALL sp_reject_claim(${id}, ${ADMIN_ID}, ${q(note)});`);
  if (outcome === 'WITHDRAW') {
    out.push(`SET @app_user_id = ${studentId(student)};`);
    out.push(`UPDATE claims SET status = 'WITHDRAWN' WHERE claim_id = ${id};`);
  }
});

out.push('');
closedReports.forEach((id) => {
  out.push(`SET @app_user_id = ${studentId(reports[id - 1][1])};`);
  out.push(`UPDATE reports SET status = 'CLOSED' WHERE report_id = ${id};`);
});
out.push('SET @app_user_id = NULL;\n');

writeFileSync(OUT, out.join('\n'));
console.log(`Wrote ${OUT}: ${students.length + admins.length} users, ${itemRows.length} item types, ` +
  `${locationRows.length} locations, ${reports.length} reports, ${claims.length} claims`);
